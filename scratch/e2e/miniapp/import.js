// Calendar import window in the Mini App / site: file, link, CalDAV, history.
const { chromium } = require('playwright');
const fs = require('fs');
const P = process.env.PLATFORM || 'telegram';
const MAX = P === 'max', WEB = P === 'web';
const BASE = MAX ? 'http://127.0.0.1:8078' : 'http://127.0.0.1:8077';
const ENTRY = MAX ? '/max/miniapp' : WEB ? '/calendar' : '/miniapp';
const TIMELINE = MAX ? '/max/timeline' : WEB ? '/calendar' : '/mini-timeline';
const initData = fs.readFileSync(__dirname + '/initdata.txt', 'utf8').trim();
const ICS = __dirname + '/../ics/Работа.ics';
const results = [];
const check = (name, ok, detail = '') => { results.push(ok); console.log(`${ok ? '✔' : '✘'} ${name}${!ok && detail ? ' — ' + detail : ''}`); };
(async () => {
  const browser = await chromium.launch();
  const mobile = !WEB;
  const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1280, height: 860 }, hasTouch: mobile, locale: 'ru-RU', timezoneId: 'Europe/Moscow', colorScheme: process.env.SCHEME || 'light' });
  if (WEB) await context.addCookies([{ name: 'planiruy_session', value: process.env.SESSION, url: BASE }]);
  const page = await context.newPage();
  const errors = [], dialogs = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', async d => { dialogs.push(d.message()); await d.accept(); });
  await page.route('https://telegram.org/js/telegram-web-app.js', r => r.fulfill({ contentType: 'application/javascript', body:
    `window.Telegram={WebApp:{initData:${JSON.stringify(initData)},platform:'android',version:'8.0',ready(){},expand(){},sendData(){},themeParams:{},colorScheme:'light'}};` }));
  await page.route('https://st.max.ru/js/max-web-app.js', r => r.fulfill({ contentType: 'application/javascript', body:
    `window.WebApp={initData:${JSON.stringify(initData)},platform:'android',ready(){},expand(){}};` }));
  await page.goto(BASE + ENTRY); await page.waitForURL(new RegExp(TIMELINE), { timeout: 10000 }).catch(() => {});
  await page.waitForTimeout(800);
  await page.click('[data-calendar-view="history"]'); await page.waitForTimeout(800);
  check('в «Истории» есть кнопка импорта', await page.isVisible('.import-open'));
  await page.click('.import-open'); await page.waitForTimeout(200);
  check('окно импорта с тремя вкладками', await page.isVisible('#importModal.open') && await page.locator('.import-tab').count() === 3);
  await page.click('#importSave'); await page.waitForTimeout(200);
  check('без файла — подсказка', /Выберите файл/.test(await page.textContent('#importError')));
  await page.setInputFiles('#importFile', ICS);
  await page.click('#importSave'); await page.waitForTimeout(2000);
  const result = (await page.textContent('#importResult')) || '';
  check('файл .ics загружен, итог показан', /добавлено 6 событий/.test(result), result + ' | ' + (await page.textContent('#importError')));
  await page.screenshot({ path: `${__dirname}/import_${P}_${process.env.SCHEME || 'light'}.png` });
  await page.click('#importModal [data-close-modal]'); await page.waitForTimeout(800);
  const history = await page.$$eval('#historyScroll .history-title', ns => ns.map(n => n.textContent));
  check('импорт появился в истории одной строкой', history.includes('Работа') && !history.includes('Синк команды'), JSON.stringify(history));
  const icon = await page.locator('#historyScroll .history-item', { hasText: 'Работа' }).locator('img').getAttribute('src');
  check('у импорта календаря своя иконка', icon && icon.includes('calendar_sync'), icon);
  await page.click('[data-calendar-view="agenda"]'); await page.waitForTimeout(500);
  const agenda = await page.$$eval('#agendaScroll .agenda-title', ns => ns.map(n => n.textContent));
  check('события импорта видны в расписании', agenda.filter(t => t === 'Синк команды').length >= 1 && agenda.includes('Конференция'), JSON.stringify(agenda.slice(0, 10)));

  await page.click('[data-calendar-view="history"]'); await page.waitForTimeout(800);
  await page.click('.import-open'); await page.click('[data-import-kind="link"]');
  await page.fill('#importUrl', 'https://calendar.google.com/calendar/ical/ru.russian%23holiday%40group.v.calendar.google.com/public/basic.ics');
  await page.click('#importSave'); await page.waitForTimeout(4000);
  check('импорт по ссылке', /Праздники России.*добавлено/.test(await page.textContent('#importResult') || ''), (await page.textContent('#importResult')) + (await page.textContent('#importError')));
  await page.fill('#importUrl', 'http://localhost/x.ics'); await page.click('#importSave'); await page.waitForTimeout(1200);
  check('внутренняя ссылка отклонена', /внутреннюю сеть/.test(await page.textContent('#importError')), await page.textContent('#importError'));
  await page.click('[data-import-kind="caldav"]');
  await page.click('#importSave'); await page.waitForTimeout(200);
  check('CalDAV: проверка пустых полей', /Заполните/.test(await page.textContent('#importError')));
  await page.fill('#importServer', 'https://example.com'); await page.fill('#importLogin', 'user'); await page.fill('#importPassword', 'secret');
  await page.click('#importSave'); await page.waitForTimeout(8000);
  check('CalDAV: понятная ошибка сервера', /CalDAV/.test(await page.textContent('#importError')), await page.textContent('#importError'));
  await page.click('[data-import-kind="file"]');
  await page.setInputFiles('#importFile', __dirname + '/../ics/formats/google_export.zip');
  await page.click('#importSave'); await page.waitForTimeout(2000);
  const zipResult = (await page.textContent('#importResult')) || '';
  check('ZIP-выгрузка Google из окна', /Рабочий Google.*добавлено 3 события/.test(zipResult) && /Дни рождения/.test(zipResult), zipResult + (await page.textContent('#importError')));
  await page.setInputFiles('#importFile', __dirname + '/../ics/formats/windows1251.ics');
  await page.click('#importSave'); await page.waitForTimeout(1500);
  check('файл в Windows-1251 из окна', /добавлено 1 событие/.test(await page.textContent('#importResult') || ''), (await page.textContent('#importResult')) + (await page.textContent('#importError')));
  await page.click('#importModal [data-close-modal]'); await page.waitForTimeout(800);
  await page.click('[data-calendar-view="agenda"]'); await page.waitForTimeout(500);
  const names = await page.$$eval('#agendaScroll .agenda-title', ns => ns.map(n => n.textContent));
  check('русские названия без «кракозябр»', names.includes('Пара по истории') && names.includes('Обзор задач'), JSON.stringify(names.slice(0, 12)));
  await page.click('[data-calendar-view="history"]'); await page.waitForTimeout(800);

  const asked = dialogs.length;
  await page.locator('#historyScroll .history-item', { hasText: 'Работа' }).locator('.history-delete').click(); await page.waitForTimeout(1500);
  check('удаление импорта календаря спрашивает подтверждение', (dialogs[asked] || '').includes('импорт календаря'), dialogs[asked]);
  check('после удаления — итог', /Импорт календаря удалён: убрано 6 событий/.test(await page.textContent('#toast')), await page.textContent('#toast'));
  await page.click('[data-calendar-view="agenda"]'); await page.waitForTimeout(500);
  const left = await page.$$eval('#agendaScroll .agenda-title', ns => ns.map(n => n.textContent));
  check('события импорта исчезли, праздники остались', !left.includes('Синк команды') && left.length > 0, JSON.stringify(left.slice(0, 6)));
  console.log('Ошибки JS:', errors.length ? errors : 'нет');
  console.log(`${results.filter(Boolean).length}/${results.length} проверок импорта в мини-приложении`);
  await browser.close();
})();
