"""One factual usage guide shared by the Telegram and MAX adapters."""


def usage_guide(platform: str) -> str:
    messenger = "Telegram" if platform == "telegram" else "MAX"
    menu_hint = (
        " Быстрее всего — кнопка «Календарь» слева от поля ввода."
        if platform == "telegram" else ""
    )
    return (
        "📖 Как пользоваться\n\n"
        "Команды: /tour — обучение за минуту; /today и /week — план на день и неделю; "
        "/calendar — календарь; /list — ближайшие дела; "
        "/reminders — уведомления; /link — общий аккаунт Telegram и MAX; "
        "/calendars — подключить Apple, Google или Яндекс Календарь; "
        "/history — история добавлений с удалением; "
        "/start — начать заново и отменить незавершённый импорт файла.\n\n"
        "1. Добавить событие\n"
        "Напишите, например: «контрольная по физике завтра с 13:00 до 14:00». "
        "Проверьте распознанные дату и время, затем подтвердите событие. Если время "
        "не указано, событие считается событием на весь день.\n\n"
        "2. Голос, фото и файлы\n"
        "Можно отправить голосовое сообщение, фотографию расписания или файл PDF, "
        "XLS/XLSX, CSV, ODS, DOCX либо TXT. Добавьте подпись, если нужно выбрать "
        "конкретную группу или раздел. Расписание с точными датами добавляется после "
        "автоматической проверки; для повторяющихся занятий бот попросит период. "
        "После импорта обязательно проверьте сводку.\n\n"
        "3. Изменить или удалить\n"
        "Напишите: «перенеси контрольную по физике на пятницу в 15:00» или "
        "«отмена контрольной по физике». Если найдено несколько событий, бот попросит "
        "выбрать нужное. Команда /history показывает всё, что вы добавляли: "
        "импортированное расписание удаляется оттуда целиком, со всеми занятиями.\n\n"
        "4. Календарь\n"
        f"Команда /calendar открывает календарь внутри {messenger}.{menu_hint} Там можно "
        "создавать, переносить, редактировать, завершать и удалять события.\n\n"
        "5. Напоминания\n"
        "Команда /reminders открывает настройки уведомлений, дневной сводки, времени "
        "сводки и функции «напомнить позже». AI-напоминания могут расходовать средства "
        "OpenRouter.\n\n"
        "6. Общий аккаунт\n"
        "Команда /link создаёт код для объединения Telegram и MAX. После объединения "
        "календарь становится общим.\n\n"
        "7. Apple, Google и Яндекс Календарь\n"
        "Команда /calendars даёт личную ссылку-подписку: подтверждённые события и "
        "занятия появятся в вашем календаре и будут обновляться сами. Менять их "
        "нужно в боте. /calendars new отключает старую ссылку.\n\n"
        "8. Импорт из другого календаря\n"
        "Пришлите файл .ics или ссылку iCal (webcal://, «закрытый адрес» Google, экспорт "
        "Яндекса) — события добавятся в календарь. /caldav загружает календари Яндекса, "
        "iCloud или Nextcloud по паролю приложения. Подробно — /import.\n\n"
        "Ограничения: распознавание нейросетью может ошибаться; пересекающееся по времени "
        "обычное событие не добавляется; событие на весь день может пересекаться с другими, "
        "но бот должен показать предупреждение."
    )
